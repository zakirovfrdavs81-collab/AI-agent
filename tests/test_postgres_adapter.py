import sqlite3
import tempfile
import unittest
from contextlib import closing
from pathlib import Path
from unittest.mock import patch

from backend import main
from backend.main import PostgreSQLConnection, insert_id


class FakeCursor:
    def fetchone(self):
        return {"id": 42}

    def __iter__(self):
        return iter(())


class FakeConnection:
    def __init__(self):
        self.statements = []

    def execute(self, statement, parameters=()):
        self.statements.append((statement, parameters))
        return FakeCursor()

    def commit(self):
        pass

    def close(self):
        pass

    def __enter__(self):
        return self

    def __exit__(self, exception_type, exception, traceback):
        return False


class PostgreSQLAdapterTests(unittest.TestCase):
    def test_execute_translates_sqlite_placeholders(self):
        raw_connection = FakeConnection()
        connection = PostgreSQLConnection(raw_connection)

        connection.execute("SELECT * FROM users WHERE email=? AND verified=?", ("a", 1))

        self.assertEqual(
            raw_connection.statements,
            [("SELECT * FROM users WHERE email=%s AND verified=%s", ("a", 1))],
        )

    def test_executescript_runs_each_statement(self):
        raw_connection = FakeConnection()
        connection = PostgreSQLConnection(raw_connection)

        connection.executescript("CREATE TABLE users (id integer); INSERT INTO users VALUES (?);")

        self.assertEqual(
            raw_connection.statements,
            [
                ("CREATE TABLE users (id integer)", ()),
                ("INSERT INTO users VALUES (%s)", ()),
            ],
        )

    def test_insert_id_uses_returning_for_postgresql(self):
        raw_connection = FakeConnection()
        connection = PostgreSQLConnection(raw_connection)

        with patch.object(main, "DATABASE_URL", "postgresql://configured"):
            value = main.insert_id(connection, "INSERT INTO users(email) VALUES (?)", ("a",))

        self.assertEqual(value, 42)
        self.assertEqual(
            raw_connection.statements,
            [("INSERT INTO users(email) VALUES (%s) RETURNING id", ("a",))],
        )

    def test_add_usage_qualifies_conflicting_messages_column_for_postgresql(self):
        raw_connection = FakeConnection()
        connection = PostgreSQLConnection(raw_connection)

        with (
            patch.object(main, "DATABASE_URL", "postgresql://configured"),
            patch.object(main, "db", return_value=connection),
        ):
            main.add_usage(7)

        self.assertEqual(len(raw_connection.statements), 1)
        statement, parameters = raw_connection.statements[0]
        self.assertIn("DO UPDATE SET messages=usage.messages+1", statement)
        self.assertEqual(parameters[0], 7)

    def test_add_usage_increments_conflicting_sqlite_row(self):
        with tempfile.TemporaryDirectory() as temp_dir:
            database_path = Path(temp_dir) / "usage.db"
            with closing(sqlite3.connect(database_path)) as connection, connection:
                connection.execute(
                    "CREATE TABLE usage(user_id INTEGER, day TEXT, messages INTEGER, PRIMARY KEY(user_id, day))"
                )
                connection.execute("INSERT INTO usage VALUES (7, '2026-10-25', 2)")

            with (
                patch.object(main, "DATABASE_URL", ""),
                patch.object(main, "DB", database_path),
                patch.object(main.time, "strftime", return_value="2026-10-25"),
            ):
                main.add_usage(7)

            with closing(sqlite3.connect(database_path)) as connection:
                row = connection.execute(
                    "SELECT messages FROM usage WHERE user_id=? AND day=?",
                    (7, "2026-10-25"),
                ).fetchone()

        self.assertEqual(row[0], 3)

    def test_database_schema_uses_postgresql_identity_columns(self):
        raw_connection = FakeConnection()
        wrapped_connection = PostgreSQLConnection(raw_connection)

        with (
            patch.object(main, "DATABASE_URL", "postgresql://configured"),
            patch.object(main, "db", return_value=wrapped_connection),
        ):
            main.init_db()

        statements = [statement for statement, _ in raw_connection.statements]
        self.assertTrue(
            any("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in statement for statement in statements)
        )
        self.assertFalse(any("AUTOINCREMENT" in statement for statement in statements))
        self.assertTrue(
            any(statement.startswith("ALTER TABLE users ADD COLUMN IF NOT EXISTS") for statement in statements)
        )

    def test_init_db_recovers_from_corrupted_sqlite_database(self):
        with tempfile.TemporaryDirectory() as temp_dir:
            db_path = Path(temp_dir) / "app.db"
            db_path.write_bytes(b"\x00\x01\x02\x03not a valid sqlite database")

            with (
                patch.object(main, "DB", db_path),
                patch.object(main, "DATABASE_URL", ""),
            ):
                main.init_db()

            self.assertTrue(db_path.exists())
            with closing(sqlite3.connect(db_path)) as connection:
                tables = connection.execute("SELECT name FROM sqlite_master WHERE type='table'").fetchall()
            self.assertIn(("users",), tables)
            self.assertTrue(any(path.name.startswith("app.db.corrupt-") for path in Path(temp_dir).iterdir()))


if __name__ == "__main__":
    unittest.main()
